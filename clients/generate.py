#!/usr/bin/env python3
"""Generate the AutoBuy client SDKs (Python, JavaScript, TypeScript) from the OpenAPI spec.

Usage:
    python clients/generate.py                      # reads clients/openapi.json
    python clients/generate.py --url http://localhost:8000/openapi.json   # refresh spec first

Emits:
    typescript/src/types.ts, typescript/src/api.ts
    javascript/src/types.d.ts, javascript/src/api.js, javascript/src/api.d.ts
    python/autobuy_client/types.py, python/autobuy_client/api.py

The HTTP/auth layers (http.ts, http.js, _http.py) are hand-written and stable;
everything above is regenerated whenever the API changes.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC_PATH = HERE / "openapi.json"

HEADER = "AUTO-GENERATED by clients/generate.py from the AutoBuy OpenAPI spec. Do not edit by hand."


# --------------------------------------------------------------------------- helpers

def snake(s: str) -> str:
    s = re.sub(r"[^0-9a-zA-Z]+", "_", s)
    s = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return s.strip("_").lower()


def camel(s: str) -> str:
    parts = snake(s).split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(s: str) -> str:
    c = camel(s)
    return c[:1].upper() + c[1:]


def ref_name(schema: dict | None) -> str | None:
    if schema and "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    return None


def op_func_name(op_id: str, path: str, method: str) -> str:
    """FastAPI operationId = <function>_<path with / { } -> _>_<method>; recover <function>."""
    suffix = path.replace("/", "_").replace("{", "_").replace("}", "_") + "_" + method
    if op_id.endswith(suffix):
        return op_id[: -len(suffix)]
    return op_id


def group_for(path: str) -> str:
    parts = [p for p in path.split("/") if p]
    if not parts:
        return "system"
    if parts[0] == "api" and len(parts) > 1:
        return parts[1]
    if parts[0] == "health":
        return "system"
    return parts[0]


# --------------------------------------------------------------------------- type mapping

class TypeMapper:
    def __init__(self, lang: str):
        self.lang = lang  # "ts" | "py"

    def map(self, schema: dict | None) -> str:
        if not schema:
            return "unknown" if self.lang == "ts" else "Any"
        if "$ref" in schema:
            return ref_name(schema)
        if "anyOf" in schema or "oneOf" in schema:
            variants = schema.get("anyOf") or schema.get("oneOf")
            mapped = [self.map(v) for v in variants]
            if self.lang == "ts":
                return " | ".join(dict.fromkeys(mapped))
            non_null = [m for m in dict.fromkeys(mapped) if m != "None"]
            inner = non_null[0] if len(non_null) == 1 else "Union[" + ", ".join(non_null) + "]"
            return f"Optional[{inner}]" if len(non_null) < len(mapped) else inner
        if "enum" in schema:
            vals = schema["enum"]
            if self.lang == "ts":
                return " | ".join(json.dumps(v) for v in vals)
            return "Literal[" + ", ".join(repr(v) for v in vals) + "]"
        t = schema.get("type")
        if t == "string":
            return "string" if self.lang == "ts" else "str"
        if t == "integer":
            return "number" if self.lang == "ts" else "int"
        if t == "number":
            return "number" if self.lang == "ts" else "float"
        if t == "boolean":
            return "boolean" if self.lang == "ts" else "bool"
        if t == "null":
            return "null" if self.lang == "ts" else "None"
        if t == "array":
            inner = self.map(schema.get("items"))
            if self.lang == "ts":
                return f"Array<{inner}>" if " | " in inner else f"{inner}[]"
            return f"List[{inner}]"
        if t == "object" or "properties" in schema or "additionalProperties" in schema:
            ap = schema.get("additionalProperties")
            if isinstance(ap, dict):
                inner = self.map(ap)
                return f"Record<string, {inner}>" if self.lang == "ts" else f"Dict[str, {inner}]"
            return "Record<string, unknown>" if self.lang == "ts" else "Dict[str, Any]"
        return "unknown" if self.lang == "ts" else "Any"


# --------------------------------------------------------------------------- operations model

def collect_ops(spec: dict) -> dict[str, list[dict]]:
    groups: dict[str, list[dict]] = {}
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            func = op_func_name(op["operationId"], path, method)
            path_params = [p for p in op.get("parameters", []) if p["in"] == "path"]
            query_params = [p for p in op.get("parameters", []) if p["in"] == "query"]
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            body_required = op.get("requestBody", {}).get("required", False)
            ok = op.get("responses", {}).get("200") or op.get("responses", {}).get("201") or {}
            resp = ok.get("content", {}).get("application/json", {}).get("schema")
            groups.setdefault(group_for(path), []).append({
                "func": func,
                "method": method,
                "path": path,
                "summary": (op.get("summary") or "").strip(),
                "description": (op.get("description") or "").strip().splitlines()[0] if op.get("description") else "",
                "path_params": path_params,
                "query_params": query_params,
                "body": body,
                "body_required": body_required,
                "resp": resp,
                "auth": "security" in op,
            })
    # ensure unique names per group
    for g, ops in groups.items():
        seen: dict[str, int] = {}
        for o in ops:
            n = o["func"]
            if n in seen:
                seen[n] += 1
                o["func"] = f"{n}_{o['method']}"
            else:
                seen[n] = 1
    return groups


# --------------------------------------------------------------------------- TypeScript

def gen_ts_types(spec: dict) -> str:
    tm = TypeMapper("ts")
    out = [f"// {HEADER}", "", "/* eslint-disable */", ""]
    for name, schema in spec["components"]["schemas"].items():
        desc = schema.get("description")
        if desc:
            out.append("/** " + desc.strip().replace("\n", " ") + " */")
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        if not props and "enum" in schema:
            out.append(f"export type {name} = {tm.map(schema)};")
            out.append("")
            continue
        out.append(f"export interface {name} {{")
        for pname, pschema in props.items():
            pdesc = pschema.get("description")
            if pdesc:
                out.append("  /** " + pdesc.strip().replace("\n", " ") + " */")
            opt = "" if pname in required else "?"
            key = pname if re.match(r"^[A-Za-z_$][A-Za-z0-9_$]*$", pname) else json.dumps(pname)
            out.append(f"  {key}{opt}: {tm.map(pschema)};")
        out.append("}")
        out.append("")
    return "\n".join(out)


def ts_query_type(op: dict, tm: TypeMapper) -> str | None:
    if not op["query_params"]:
        return None
    fields = []
    for q in op["query_params"]:
        opt = "" if q.get("required") else "?"
        fields.append(f"{q['name']}{opt}: {tm.map(q.get('schema'))}")
    return "{ " + "; ".join(fields) + " }"


def ts_signature(op: dict, tm: TypeMapper) -> tuple[str, str, list[str]]:
    """Return (params, return type, doc lines)."""
    params = []
    for p in op["path_params"]:
        params.append(f"{camel(p['name'])}: {tm.map(p.get('schema'))}")
    if op["body"] is not None:
        params.append(f"body{'' if op['body_required'] else '?'}: {tm.map(op['body'])}")
    qt = ts_query_type(op, tm)
    if qt:
        all_opt = all(not q.get("required") for q in op["query_params"])
        params.append(f"query{'?' if all_opt else ''}: {qt}")
    ret = tm.map(op["resp"]) if op["resp"] is not None else "unknown"
    return ", ".join(params), ret, []


def ts_call_args(op: dict) -> str:
    path_expr = '"' + re.sub(r"\{(\w+)\}", lambda m: '" + encodeURIComponent(String(' + camel(m.group(1)) + ')) + "', op["path"]) + '"'
    path_expr = path_expr.replace(' + ""', "").replace('"" + ', "")
    parts = [json.dumps(op["method"].upper()), path_expr]
    opts = []
    if op["body"] is not None:
        opts.append("body")
    if op["query_params"]:
        opts.append("query")
    opts.append("auth: " + ("true" if op["auth"] else "false"))
    parts.append("{ " + ", ".join(opts) + " }")
    return ", ".join(parts)


def gen_ts_api(spec: dict, groups: dict[str, list[dict]]) -> str:
    tm = TypeMapper("ts")
    used = sorted({n for ops in groups.values() for op in ops for n in _refs_in_ops([op])})
    out = [f"// {HEADER}", "", 'import type { HttpTransport } from "./http.js";']
    if used:
        out.append("import type {")
        out.extend(f"  {n}," for n in used)
        out.append('} from "./types.js";')
    out.append("")
    for g, ops in groups.items():
        cls = pascal(g) + "Api"
        out.append(f"/** `{g}` endpoints. */")
        out.append(f"export class {cls} {{")
        out.append("  constructor(private readonly http: HttpTransport) {}")
        out.append("")
        for op in ops:
            params, ret, _ = ts_signature(op, tm)
            doc = op["summary"] or op["description"] or f"{op['method'].upper()} {op['path']}"
            out.append(f"  /** {doc} — `{op['method'].upper()} {op['path']}` */")
            out.append(f"  {camel(op['func'])}({params}): Promise<{ret}> {{")
            out.append(f"    return this.http.request<{ret}>({ts_call_args(op)});")
            out.append("  }")
            out.append("")
        out.append("}")
        out.append("")
    out.append("/** All resource groups, keyed by API module. */")
    out.append("export function buildApi(http: HttpTransport) {")
    out.append("  return {")
    for g in groups:
        out.append(f"    {camel(g)}: new {pascal(g) + 'Api'}(http),")
    out.append("  } as const;")
    out.append("}")
    out.append("")
    out.append("export type Api = ReturnType<typeof buildApi>;")
    out.append("")
    return "\n".join(out)


def _refs_in_schema(schema: dict | None, acc: set[str]) -> None:
    if not schema:
        return
    if "$ref" in schema:
        acc.add(ref_name(schema))
    for key in ("items", "additionalProperties"):
        if isinstance(schema.get(key), dict):
            _refs_in_schema(schema[key], acc)
    for v in schema.get("anyOf", []) + schema.get("oneOf", []):
        _refs_in_schema(v, acc)


def _refs_in_ops(ops: list[dict]) -> set[str]:
    acc: set[str] = set()
    for op in ops:
        _refs_in_schema(op["body"], acc)
        _refs_in_schema(op["resp"], acc)
        for q in op["query_params"] + op["path_params"]:
            _refs_in_schema(q.get("schema"), acc)
    return acc


# --------------------------------------------------------------------------- JavaScript

def gen_js_api(spec: dict, groups: dict[str, list[dict]]) -> tuple[str, str]:
    """Return (api.js, api.d.ts)."""
    tm = TypeMapper("ts")
    js = [f"// {HEADER}", ""]
    dts = [f"// {HEADER}", "", 'import type { HttpTransport } from "./http.js";']
    used = sorted({n for ops in groups.values() for op in ops for n in _refs_in_ops([op])})
    if used:
        dts.append("import type {")
        dts.extend(f"  {n}," for n in used)
        dts.append('} from "./types.js";')
    dts.append("")
    for g, ops in groups.items():
        cls = pascal(g) + "Api"
        js.append(f"/** `{g}` endpoints. */")
        js.append(f"export class {cls} {{")
        js.append("  /** @param {import('./http.js').HttpTransport} http */")
        js.append("  constructor(http) {")
        js.append("    this.http = http;")
        js.append("  }")
        js.append("")
        dts.append(f"/** `{g}` endpoints. */")
        dts.append(f"export declare class {cls} {{")
        dts.append("  constructor(http: HttpTransport);")
        for op in ops:
            params, ret, _ = ts_signature(op, tm)
            doc = op["summary"] or op["description"] or f"{op['method'].upper()} {op['path']}"
            js_params = []
            for p in op["path_params"]:
                js_params.append(camel(p["name"]))
            if op["body"] is not None:
                js_params.append("body")
            if op["query_params"]:
                js_params.append("query")
            js.append("  /**")
            js.append(f"   * {doc} — `{op['method'].upper()} {op['path']}`")
            for p in op["path_params"]:
                js.append(f"   * @param {{{tm.map(p.get('schema'))}}} {camel(p['name'])}")
            if op["body"] is not None:
                js.append(f"   * @param {{import('./types.js').{tm.map(op['body'])}}} body")
            if op["query_params"]:
                js.append(f"   * @param {{{ts_query_type(op, tm)}}} [query]")
            rt = ret if ret in ("unknown",) or "[" in ret else f"import('./types.js').{ret}"
            if ret.endswith("[]"):
                rt = f"import('./types.js').{ret[:-2]}[]"
            js.append(f"   * @returns {{Promise<{rt}>}}")
            js.append("   */")
            js.append(f"  {camel(op['func'])}({', '.join(js_params)}) {{")
            js.append(f"    return this.http.request({ts_call_args(op)});")
            js.append("  }")
            js.append("")
            dts.append(f"  /** {doc} — `{op['method'].upper()} {op['path']}` */")
            dts.append(f"  {camel(op['func'])}({params}): Promise<{ret}>;")
        js.append("}")
        js.append("")
        dts.append("}")
        dts.append("")
    js.append("/** All resource groups, keyed by API module. */")
    js.append("export function buildApi(http) {")
    js.append("  return {")
    for g in groups:
        js.append(f"    {camel(g)}: new {pascal(g) + 'Api'}(http),")
    js.append("  };")
    js.append("}")
    js.append("")
    dts.append("export interface Api {")
    for g in groups:
        dts.append(f"  readonly {camel(g)}: {pascal(g) + 'Api'};")
    dts.append("}")
    dts.append("export declare function buildApi(http: HttpTransport): Api;")
    dts.append("")
    return "\n".join(js), "\n".join(dts)


# --------------------------------------------------------------------------- Python

def gen_py_types(spec: dict) -> str:
    tm = TypeMapper("py")
    out = [f'"""{HEADER}"""', "from __future__ import annotations", "",
           "import sys", "from typing import Any, Dict, List, Literal, Optional, Union", "",
           "if sys.version_info >= (3, 11):", "    from typing import NotRequired, TypedDict",
           "else:  # pragma: no cover", "    from typing_extensions import NotRequired, TypedDict", "", ""]
    for name, schema in spec["components"]["schemas"].items():
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        if not props and "enum" in schema:
            out.append(f"{name} = {tm.map(schema)}")
            out.append("")
            continue
        out.append(f"class {name}(TypedDict):")
        desc = (schema.get("description") or "").strip().replace("\n", " ")
        out.append(f'    """{desc or name}."""' if not desc.endswith(".") else f'    """{desc}"""')
        if not props:
            out.append("    pass")
        for pname, pschema in props.items():
            t = tm.map(pschema)
            if pname not in required:
                t = f"NotRequired[{t}]"
            out.append(f"    {pname}: {t}")
        out.append("")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def _opt(t: str) -> str:
    return t if t.startswith("Optional[") else f"Optional[{t}]"


def py_signature(op: dict, tm: TypeMapper) -> tuple[str, str]:
    params = ["self"]
    for p in op["path_params"]:
        params.append(f"{snake(p['name'])}: {tm.map(p.get('schema'))}")
    if op["body"] is not None:
        bt = tm.map(op["body"])
        params.append(f"body: {bt}" if op["body_required"] else f"body: {_opt(bt)} = None")
    if op["query_params"]:
        params.append("*")
        for q in op["query_params"]:
            qt = tm.map(q.get("schema"))
            if q.get("required"):
                params.append(f"{snake(q['name'])}: {qt}")
            else:
                params.append(f"{snake(q['name'])}: {_opt(qt)} = None")
    ret = tm.map(op["resp"]) if op["resp"] is not None else "Any"
    return ", ".join(params), ret


def py_call(op: dict, awaitable: bool) -> list[str]:
    path_expr = '"' + re.sub(r"\{(\w+)\}", lambda m: '" + _q(' + snake(m.group(1)) + ') + "', op["path"]) + '"'
    path_expr = path_expr.replace(' + ""', "").replace('"" + ', "")
    kwargs = [f"auth={op['auth']}"]
    if op["body"] is not None:
        kwargs.append("body=body")
    if op["query_params"]:
        q = ", ".join(f'"{q["name"]}": {snake(q["name"])}' for q in op["query_params"])
        kwargs.append("query={" + q + "}")
    prefix = "return await " if awaitable else "return "
    return [f'        {prefix}self._http.request("{op["method"].upper()}", {path_expr}, {", ".join(kwargs)})']


def gen_py_api(spec: dict, groups: dict[str, list[dict]]) -> str:
    tm = TypeMapper("py")
    used = sorted({n for ops in groups.values() for op in ops for n in _refs_in_ops([op])})
    out = [f'"""{HEADER}"""', "from __future__ import annotations", "",
           "from typing import Any, Dict, List, Optional, Union", "",
           "from ._http import AsyncTransport, SyncTransport, _q"]
    if used:
        out.append("from .types import (")
        out.extend(f"    {n}," for n in used)
        out.append(")")
    out.append("")
    out.append("")
    for g, ops in groups.items():
        for is_async in (False, True):
            cls = ("Async" if is_async else "") + pascal(g) + "Api"
            transport = "AsyncTransport" if is_async else "SyncTransport"
            out.append(f"class {cls}:")
            out.append(f'    """`{g}` endpoints{" (async)" if is_async else ""}."""')
            out.append("")
            out.append(f"    def __init__(self, http: {transport}) -> None:")
            out.append("        self._http = http")
            out.append("")
            for op in ops:
                params, ret = py_signature(op, tm)
                doc = op["summary"] or op["description"] or f"{op['method'].upper()} {op['path']}"
                out.append(f"    {'async ' if is_async else ''}def {snake(op['func'])}({params}) -> {ret}:")
                out.append(f'        """{doc} — ``{op["method"].upper()} {op["path"]}``."""')
                out.extend(py_call(op, is_async))
                out.append("")
            out.append("")
    for is_async in (False, True):
        cls = ("Async" if is_async else "") + "Api"
        transport = "AsyncTransport" if is_async else "SyncTransport"
        out.append(f"class {cls}:")
        out.append('    """All resource groups, keyed by API module."""')
        out.append("")
        out.append(f"    def __init__(self, http: {transport}) -> None:")
        for g in groups:
            out.append(f"        self.{snake(g)} = {('Async' if is_async else '') + pascal(g) + 'Api'}(http)")
        out.append("")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# --------------------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--url", help="fetch a fresh spec from this URL and save it to clients/openapi.json")
    ap.add_argument("--spec", default=str(SPEC_PATH), help="path to openapi.json")
    args = ap.parse_args()

    if args.url:
        with urllib.request.urlopen(args.url, timeout=10) as r:
            spec = json.load(r)
        SPEC_PATH.write_text(json.dumps(spec, indent=2, sort_keys=False) + "\n")
        print(f"saved spec -> {SPEC_PATH}")
    else:
        spec = json.loads(Path(args.spec).read_text())

    groups = collect_ops(spec)
    n_ops = sum(len(v) for v in groups.values())
    n_types = len(spec["components"]["schemas"])

    outputs = {
        HERE / "typescript/src/types.ts": gen_ts_types(spec),
        HERE / "typescript/src/api.ts": gen_ts_api(spec, groups),
        HERE / "javascript/src/types.d.ts": gen_ts_types(spec),
        HERE / "python/autobuy_client/types.py": gen_py_types(spec),
        HERE / "python/autobuy_client/api.py": gen_py_api(spec, groups),
    }
    js, dts = gen_js_api(spec, groups)
    outputs[HERE / "javascript/src/api.js"] = js
    outputs[HERE / "javascript/src/api.d.ts"] = dts
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(HERE)}")
    print(f"{n_types} schemas, {n_ops} operations in {len(groups)} groups: {', '.join(groups)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
